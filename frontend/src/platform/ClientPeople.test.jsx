import React from 'react';
import {render,screen,fireEvent,cleanup} from '@testing-library/react';
import {it,expect,vi,afterEach} from 'vitest';
import {ClientPeople} from './ClientPeople.jsx';
afterEach(()=>{cleanup();vi.restoreAllMocks();});
it('creates a structured contact and saves the media communication toggle',async()=>{
 global.fetch=vi.fn(async(path,o)=>({ok:true,json:async()=>o.method==='GET'?[]:{id:1,...JSON.parse(o.body)}}));
 render(<ClientPeople clientId={1}/>);
 await screen.findByText('Noch keine strukturierten Kontakte hinterlegt.');
 fireEvent.click(screen.getByRole('button',{name:'Kontakt hinzufügen'}));
 for(const [label,value] of [['Name','Anna'],['E-Mail','anna@example.com'],['Telefon','1234'],['Position','Leitung'],['Verantwortungsbereich','Presse']])fireEvent.change(screen.getByLabelText(label),{target:{value}});
 fireEvent.click(screen.getByRole('button',{name:'Kommuniziert mit Medien'}));
 fireEvent.click(screen.getByRole('button',{name:'Kontakt speichern'}));
 await screen.findByText('Anna');
 expect(screen.getByText('anna@example.com')).toBeTruthy();
 expect(screen.getByRole('button',{name:'Kommuniziert mit Medien'}).getAttribute('aria-pressed')).toBe('true');
 fireEvent.click(screen.getByRole('button',{name:'Kommuniziert mit Medien'}));
 await screen.findByText('News · Nein');
 expect(JSON.parse(fetch.mock.calls.at(-1)[1].body).media_contact).toBe(false);
});
