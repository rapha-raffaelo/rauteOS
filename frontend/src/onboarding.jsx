import React from 'react';
import { createRoot } from 'react-dom/client';
import { OnboardingPage } from './components/OnboardingPage.jsx';
import './onboarding.css';
import {OnboardingAccess} from './components/OnboardingAccess.jsx';
import {createDemoApi} from './onboardingDemo.js';
const demo = document.getElementById('onboarding-demo');
const demoApi = demo ? createDemoApi(JSON.parse(demo.textContent)) : null;
const slug = /^\/onboarding\/([a-z0-9-]+)\/?$/.exec(window.location.pathname)?.[1];
createRoot(document.getElementById('onboarding-root')).render(slug && slug !== 'demo' ? <OnboardingAccess slug={slug}/> : <OnboardingPage demoApi={demoApi} />);
